// Isolated Telegram and scheduler checks. No Telegram/Buffer requests or real media.
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const crypto = require('node:crypto');
const assert = require('node:assert/strict');
const root = path.resolve(__dirname, '..');
const directory = fs.mkdtempSync(path.join(root, 'temp/template-check-'));
const local = name => { assert.ok(name === '/files' || name.startsWith('/files/')); return path.join(directory, name.slice(7)); };
const fakeFs = {};
for (const method of ['readFileSync', 'writeFileSync', 'openSync', 'unlinkSync', 'statSync', 'existsSync', 'readdirSync']) fakeFs[method] = (name, ...args) => fs[method](local(name), ...args);
fakeFs.renameSync = (from, to) => fs.renameSync(local(from), local(to));
fakeFs.closeSync = fd => fs.closeSync(fd);
const source = name => fs.readFileSync(path.join(root, 'workflows/code/' + name + '.js'), 'utf8');
const config = { allowedChatIds: [456], allowedUserIds: [456], services: ['facebook', 'threads', 'tiktok'], publicBaseUrl: 'https://example.com', mediaWebhookId: 'media', albumQuietMs: 3000, queue: { enabled: true, hours: [9, 14, 20], lowWatermark: 3, maxPendingPerChannel: 9 } };
let time = Date.parse('2026-11-09T01:50:00Z');
class Clock extends Date { constructor(...args) { super(...(args.length ? args : [time])); } static now() { return time; } }
let remote = [];
let apiFailed = false;
let hasChannels = true;
const channels = config.services.map(service => ({ id: service, service, name: service }));
const run = (name, json = {}, work) => {
  const prefix = name === 'telegram-album-intake' ? source('telegram-image-crop-intake') + '\n' + source('telegram-list-import-intake') + '\n' : '';
  return JSON.parse(JSON.stringify(vm.runInNewContext('(()=>{const publisherConfig=' + JSON.stringify(config) + ';\n' + source('telegram-queue-store') + '\n' + prefix + source(name) + '\n})()', {
    require: name => name === 'fs' ? fakeFs : crypto, Date: Clock, $runIndex: 0, $input: { first: () => ({ json }) },
    $: name => ({ isExecuted: hasChannels, itemMatching: () => ({ json: work }), first: () => ({ json: name === 'Queue Pending Posts' ? apiFailed ? { errors: [{ message: 'offline' }] } : { data: { posts: { edges: remote.map(node => ({ node })), pageInfo: { hasNextPage: false } } } } : { data: { channels } } }) }),
  })));
};
const state = () => JSON.parse(fakeFs.readFileSync('/files/telegram-content-queue.json', 'utf8'));
const write = value => fakeFs.writeFileSync('/files/telegram-content-queue.json', JSON.stringify(value));
const initial = () => ({ version: 1, posts: [], notices: [], commands: {}, lowNotified: {} });
let messageId = 1;
const message = extra => ({ message_id: messageId++, chat: { id: 456, type: 'private' }, from: { id: 456 }, ...extra });
const intake = value => run('telegram-album-intake', { message: value });
const command = text => {
  const routed = intake(message({ text }))[0].json;
  assert.equal(routed.queueCommand, true);
  return run('telegram-queue-command', routed)[0].json;
};
const upload = (caption = 'Bài mẫu 💌', extra = {}) => intake(message({ photo: [{ file_id: 'photo', file_size: 100 }], caption, ...extra }))[0].json;
const save = context => {
  const name = 'queue_' + crypto.createHash('md5').update(String(context.messageId)).digest('hex') + '.jpg';
  fakeFs.writeFileSync('/files/' + name, 'image-content');
  return run('telegram-queue-save', { ...context, assets: [{ image: { url: 'https://example.com/' + name } }] })[0].json;
};
const drain = (response = 'success') => {
  const creates = [];
  for (let index = 0; index < 100; index++) {
    const work = run('telegram-queue-work')[0].json;
    if (!work.hasWork) return creates;
    if (work.action === 'notify') run('telegram-queue-notified', {}, work);
    else if (work.action === 'create') {
      creates.push(work);
      run('telegram-queue-result', response === 'success' ? { data: { createPost: { __typename: 'PostActionSuccess', post: { id: work.queuePostId + ':' + work.channelId, status: 'scheduled' } } } } : { error: 'connection closed' }, work);
    } else run('telegram-queue-result', { data: { post: { id: work.postId, status: 'sent' } } }, work);
  }
  assert.fail('Worker did not finish');
};
write(initial());
